// Generates docs/COMPONENTS.md from the story registry and docs/verification.json from the Playwright report.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { STORIES } from '../src/workbench/stories/index';

const reportPath = new URL('../reports/report.json', import.meta.url);
// Optional newer run of tests/interaction.spec.ts only; when present it replaces the interaction results of the full report.
const interactionPath = new URL('../reports/report-interaction.json', import.meta.url);
const shotsPath = new URL('../docs/screenshots.json', import.meta.url);

/**
 * Evidence tiers, each earned only by passing tests (never by a status label):
 * - render:      every generated render test passed (8 widths x light/dark, no overflow, no console errors)
 * - a11y:        every axe WCAG 2.1 AA test passed (320 and 1024px, light and dark)
 * - interaction: at least one hand-written interaction test for this component ran in Chromium and none failed
 * - browser:     interaction-tested AND screenshots captured at mobile/desktop x light/dark (docs/screenshots.json)
 * Components without a tier are "not verified" at that level.
 */
type Tier = { render: [number, number]; a11y: [number, number]; interaction: [number, number] };
const tiers = new Map<string, Tier>();
const get = (id: string): Tier => { let t = tiers.get(id); if (!t) { t = { render: [0, 0], a11y: [0, 0], interaction: [0, 0] }; tiers.set(id, t); } return t; };
const known = new Set(STORIES.filter((x) => x.status !== 'planned').map((x) => x.id));
const hasInteractionRun = existsSync(interactionPath);
for (const [path, interactionOnly] of [[reportPath, false], [interactionPath, true]] as const) if (existsSync(path)) {
  const rep = JSON.parse(readFileSync(path, 'utf8'));
  const walk = (s: any, storyId: string | undefined) => {
    const id = known.has(s.title) ? (s.title as string) : storyId;
    for (const sp of s.specs ?? []) for (const t of sp.tests ?? []) {
      const ok = (t.results ?? []).length > 0 && (t.results ?? []).every((r: any) => r.status === 'passed');
      const annotated: string[] = (t.annotations ?? []).filter((a: any) => a.type === 'story').map((a: any) => a.description);
      if (annotated.length) { if (hasInteractionRun !== interactionOnly) continue; for (const a of annotated) if (known.has(a)) get(a).interaction[ok ? 0 : 1]++; continue; }
      if (!id || interactionOnly) continue;
      const kind = /axe/.test(sp.title) ? 'a11y' : /renders/.test(sp.title) ? 'render' : undefined;
      if (kind) get(id)[kind][ok ? 0 : 1]++;
    }
    for (const c of s.suites ?? []) walk(c, id);
  };
  for (const s of rep.suites ?? []) walk(s, undefined);
}
const shots: { captured: string[] } = existsSync(shotsPath) ? JSON.parse(readFileSync(shotsPath, 'utf8')) : { captured: [] };
const pass = (c: [number, number]) => c[0] > 0 && c[1] === 0;
const level = (id: string) => {
  const t = tiers.get(id);
  const render = !!t && pass(t.render), a11y = !!t && pass(t.a11y), interaction = !!t && pass(t.interaction);
  const failing = !!t && (t.render[1] > 0 || t.a11y[1] > 0 || t.interaction[1] > 0);
  return { render, a11y, interaction, browser: interaction && shots.captured.includes(id), failing };
};
const verified = STORIES.filter((s) => s.status !== 'planned' && level(s.id).render && level(s.id).a11y).map((s) => s.id).sort();
const failing = STORIES.filter((s) => level(s.id).failing).map((s) => s.id);
writeFileSync(new URL('../docs/verification.json', import.meta.url), JSON.stringify({
  verified,
  failing,
  tiers: Object.fromEntries(STORIES.filter((s) => s.status !== 'planned').map((s) => [s.id, level(s.id)])),
  note: 'verified = render + axe tiers passed. interaction = hand-written keyboard/pointer tests passed. browser = interaction-tested and screenshotted. See scripts/registry-report.ts for exact definitions.',
}, null, 2));
const mark = (b: boolean) => (b ? 'yes' : 'no');

const by = new Map<string, typeof STORIES>();
for (const s of STORIES) by.set(s.category, [...(by.get(s.category) ?? []), s]);
let md = `# Component registry\n\nGenerated by \`npm run registry\`. Do not edit by hand.\n\n- Stories: ${STORIES.length}\n- Implemented: ${STORIES.filter((s) => s.status === 'implemented').length}, partial: ${STORIES.filter((s) => s.status === 'partial').length}\n- Render + axe tested: ${verified.length}\n- Interaction-tested: ${STORIES.filter((s) => level(s.id).interaction).length}\n- Browser-verified (interaction + screenshots): ${STORIES.filter((s) => level(s.id).browser).length}\n\nTiers are earned only by passing tests (docs/verification.json). A component marked "no" in a column is **not verified at that level**; status labels never imply verification.\n\n`;
for (const [cat, items] of by) {
  md += `## ${cat}\n\n| Component | Layer | Status | Render | A11y (axe) | Interaction | Browser | Source |\n|---|---|---|---|---|---|---|---|\n`;
  for (const s of items) md += `| ${s.title} | ${s.layer} | ${s.status} | ${s.status === 'planned' ? '-' : mark(level(s.id).render)} | ${s.status === 'planned' ? '-' : mark(level(s.id).a11y)} | ${s.status === 'planned' ? '-' : mark(level(s.id).interaction)} | ${s.status === 'planned' ? '-' : mark(level(s.id).browser)} | ${s.source} |\n`;
  md += '\n';
  for (const s of items) { md += `### ${s.title}\n\n${s.purpose}\n\n- **Use for:** ${s.variants.join(', ')}\n- **Props:** ${s.props.join('; ')}\n- **Accessibility:** ${s.a11y}\n- **Responsive:** ${s.responsive}\n${s.gaps ? `- **Known gaps:** ${s.gaps}\n` : ''}\n`; }
}
writeFileSync(new URL('../docs/COMPONENTS.md', import.meta.url), md);
console.log(`render+axe ${verified.length}, interaction ${STORIES.filter((s) => level(s.id).interaction).length}, browser ${STORIES.filter((s) => level(s.id).browser).length} of ${STORIES.filter((s) => s.status !== 'planned').length}; failing: ${failing.join(', ') || 'none'}`);
