import { useState } from 'react';
import { Notice, Select } from '@/design-system';
import { InvoiceSummary, type Invoice } from '@/features';
import { ResourceView } from '@/views/shared/ResourceView';
import { useApi, useApiQuery } from '../../data/DataProvider';
import { PageHeader } from '../../components/PageHeader';
import { date, money } from '../../format';
import type { InvoiceRecord } from '../../domain/types';

const toUi = (i: InvoiceRecord): Invoice => ({ number: i.number, state: i.state, issued: date(i.issuedOn), due: i.dueOn ? date(i.dueOn) : undefined, paidOn: i.paidOn ? date(i.paidOn) : undefined, total: money(i.total), tax: `${i.taxLabel ?? 'Tax'}: ${money(i.tax)}`, lines: i.lines.map((l) => ({ id: l.id, description: l.description, amount: money(l.amount) })) });

export default function InvoiceDetail({ id }: { id: string }) {
  const api = useApi();
  const res = useApiQuery((a) => a.getInvoice(id), [id]);
  const methods = useApiQuery((a) => a.listPaymentMethods());
  const [pm, setPm] = useState<string | null>(null);
  const [note, setNote] = useState<{ tone: 'good' | 'bad'; text: string }>();
  return (
    <div className="grid gap-5">
      <PageHeader title="Invoice" crumbs={[{ label: 'Billing', to: '/app/billing' }, { label: 'Invoices', to: '/app/billing/invoices' }, { label: 'Detail' }]} />
      {note ? <Notice tone={note.tone}>{note.text}</Notice> : null}
      <ResourceView res={res} reload={res.reload} label="Loading invoice">
        {(i) => (
          <div className="grid max-w-3xl gap-4">
            {(i.state === 'open' || i.state === 'overdue') && methods.status === 'ready' ? (
              <Select label="Pay with" value={pm ?? methods.data.find((m) => m.isDefault)?.id ?? null} onValueChange={setPm} options={methods.data.map((m) => ({ value: m.id, label: `${m.brand.toUpperCase()} •••• ${m.last4}`, description: m.last4 === '0087' ? 'Prototype: this card is declined.' : undefined }))} />
            ) : null}
            <InvoiceSummary
              invoice={toUi(i)}
              onPay={async () => {
                const method = pm ?? methods.data?.find((m) => m.isDefault)?.id;
                if (!method) { setNote({ tone: 'bad', text: 'Add a payment method first.' }); return; }
                try { const r = await api.payInvoice(i.id, method); setNote({ tone: 'good', text: `Payment received. Receipt ${r.receipt}. Suspended services resume within a minute.` }); } catch (e) { setNote({ tone: 'bad', text: e instanceof Error ? e.message : 'Payment failed.' }); }
              }}
              onDownload={() => setNote({ tone: 'good', text: 'In production this downloads the PDF generated by the billing backend.' })}
            />
          </div>
        )}
      </ResourceView>
    </div>
  );
}
